  // Curated 100 Premium Oversized T-Shirt Designs
  // -------------------------------------------------------------
  const curatedPrefixes = ["Cyberpunk", "Tokyo Shift", "Aesthetic", "Retro Wave", "Gothic Grunge", "Urban Nomad", "Minimalist", "Ghost Tech", "Vintage Club", "Midnight"];
